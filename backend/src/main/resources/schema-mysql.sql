-- 只创建本作业的表，不 DROP 或清空现有数据。
CREATE TABLE IF NOT EXISTS `user` (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    userName VARCHAR(20) NOT NULL,
    userPassword VARCHAR(512) NOT NULL,
    updateTime DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    createTime DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    isDelete TINYINT NOT NULL DEFAULT 0,
    userRole INT NOT NULL DEFAULT 0,
    activeName VARCHAR(20) GENERATED ALWAYS AS (CASE WHEN isDelete = 0 THEN LOWER(userName) ELSE NULL END) STORED,
    UNIQUE KEY uk_active_username (activeName)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS mybatis_test_user (
    id BIGINT NOT NULL PRIMARY KEY,
    name VARCHAR(30),
    age INT,
    email VARCHAR(50)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
